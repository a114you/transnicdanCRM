const phraseMaps: Record<Exclude<Language, "ru">, Record<string, string>> = {
  ro: romanianPhraseMap,
  en: englishPhraseMap,
};

export function translatePhrase(value: string, language: Language): string {
  if (language === "ru" || !value.trim()) return value;

  const trimmed = value.trim();
  const map = phraseMaps[language];
  const exact = map[trimmed];
  if (exact) {
    return value.replace(trimmed, exact);
  }

  let translated = value;
  const entries = Object.entries(map).sort((a, b) => b[0].length - a[0].length);
  for (const [source, target] of entries) {
    translated = translated.replaceAll(source, target);
  }
  return translated;
}

export function getInitialLanguage(): Language {
  if (typeof window === "undefined") return "ru";
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (saved === "ro" || saved === "ru" || saved === "en") return saved;
  const cookieLanguage = document.cookie
    .split("; ")
    .find((part) => part.startsWith(`${LANGUAGE_STORAGE_KEY}=`))
    ?.split("=")[1];
  if (cookieLanguage === "ro" || cookieLanguage === "en") return cookieLanguage;
  return "ru";
}

export function tr(value: string, language: Language): string {
  return translatePhrase(value, language);
}
